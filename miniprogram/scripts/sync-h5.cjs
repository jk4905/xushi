'use strict';
// Reuse the verified H5 domain and original recipe; never scrape or infer recipe content.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = path.resolve(root, '../h5');
const check = process.argv.includes('--check');
if (check && process.argv.includes('--images')) throw new Error('--check cannot be used with --images');
function sync(file, content) {
  const target = path.join(root, file);
  if (!check) {
    fs.writeFileSync(target, content);
    return;
  }
  let current;
  try {
    current = fs.readFileSync(target, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== content) {
    console.error('Out of sync: ' + file);
    process.exitCode = 1;
  }
}
const html = fs.readFileSync(path.join(source, 'weekend-menu-prototype.html'), 'utf8');
const meal = html.match(/<script id="meal-logic">([\s\S]*?)<\/script>/)[1];
const header = '// Generated by scripts/sync-h5.cjs from the existing H5; platform adaptations only.\n';
sync('core/meal.js', header + meal.replace('globalThis.MealModel=MealModel;', 'module.exports=MealModel;'));
let household = fs.readFileSync(path.join(source, 'weekend-household-model.js'), 'utf8');
household = household.replace('globalThis.MealModel', "require('./meal')")
  .replaceAll('Object.hasOwn(', 'Object.prototype.hasOwnProperty.call(')
  .replace(/    let url;[\s\S]*?    return url.href;/, "    return require('./source-url').normalize(trimmed, message);")
  .replace('globalThis.HouseholdModel = HouseholdModel;', '');
sync('core/household.js', header + household);
const context = vm.createContext({});
const raw = html.match(/const beefSteps=(\[[^\n]+\]);/)[1];
const beefSteps = JSON.parse(raw);
const rawDishes = html.match(/const dishes=(\[[^\n]+\]);/)[1];
const dishes = vm.runInContext(rawDishes, context, {timeout:1000})
  .map(({key,name,kind}) => ({id:key,name,kind}));
const seedRecipes = dishes.map(d => ({...d,steps:d.id==='beef'?beefSteps.map(({title,text})=>({title,text})):[]}));
sync('core/content.js', header + 'const beefSteps = '+JSON.stringify(beefSteps,null,2)+';\nconst seedRecipes = '+JSON.stringify(seedRecipes,null,2)+';\nfunction stepImage(recipe,index) { return recipe.id === "beef" && recipe.steps[index] && beefSteps[index] && recipe.steps[index].text === beefSteps[index].text ? "/assets/step-"+index+".png" : ""; }\nmodule.exports = {beefSteps,seedRecipes,stepImage};\n');
// Rendering SVGs is an optional development action; generated PNGs ship with the project.
if (process.argv.includes('--images')) {
  const sharp = require(process.env.XUSHI_SHARP || 'sharp');
  const stepStart = html.indexOf('    function stepArt(index) {');
  const stepEnd = html.indexOf('\n    }', stepStart) + 6;
  const foodStart = html.indexOf("    function foodArt(kind='meal') {");
  const foodEnd = html.indexOf('\n    }', foodStart) + 6;
  vm.runInContext(html.slice(stepStart, stepEnd)+html.slice(foodStart,foodEnd), context);
  (async () => {
    for (let i=0;i<10;i++) {
      const svg = context.stepArt(i).match(/<svg[\s\S]*?<\/svg>/)[0].replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ');
      await sharp(Buffer.from(svg)).resize(640).png().toFile(path.join(root,'assets/step-'+i+'.png'));
    }
    for(const kind of ['beef','broccoli','rice','meal']) {
      const svg = context.foodArt(kind).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ');
      await sharp(Buffer.from(svg)).resize(kind==='meal'?720:240).png().toFile(path.join(root,'assets/'+kind+'.png'));
    }
  })().catch(error=>{console.error(error);process.exitCode=1;});
}
